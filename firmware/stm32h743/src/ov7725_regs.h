#pragma once

#include <stdint.h>

// OV7725 register table for RGB565 QVGA (320x240) output, SCCB address 0x21,
// 8-bit registers. Source: OpenMV ov7725.c. Measured on this board's camera
// bus (`i2c` console command answers 0x21 at both PWDN levels, not 0x3C) --
// this module is an OV7725/OV7670, not the OV5640 the rest of camera.cpp was
// first written against.
struct Reg8 {
  uint8_t reg;
  uint8_t val;
};

constexpr uint8_t kOv7725End = 0xFF;

static const Reg8 kOv7725Init[] = {
    {0x0C, 0x10},                                                          // COM3: 0xD0 = also flip + mirror
    {0x0D, 0x41}, {0x11, 0x03},                                            // PLL x4, CLKRC /4 -> 12 MHz internal clock
    {0x12, 0x46},                                                          // COM7: QVGA, RGB565
    {0x17, 0x3F}, {0x18, 0x50}, {0x19, 0x03}, {0x1A, 0x78}, {0x32, 0x00},  // sensor window
    {0x29, 0x50}, {0x2C, 0x78}, {0x2A, 0x00},                             // output 320 x 240
    {0x15, 0x00},                                                         // COM10: default sync polarities
    {0x42, 0x7F}, {0x4D, 0x09},
    {0x63, 0xF0}, {0x64, 0x1F}, {0x65, 0x20}, {0x66, 0x00}, {0x67, 0x00},  // AWB + DSP
    {0x0F, 0xC5}, {0x14, 0x11},
    {0x22, 0x7F}, {0x23, 0x03}, {0x24, 0x75}, {0x25, 0x63}, {0x26, 0xD1},  // banding filter, AE targets
    {0x7E, 0x0C}, {0x7F, 0x16}, {0x80, 0x2A}, {0x81, 0x4E}, {0x82, 0x61}, {0x83, 0x6F}, {0x84, 0x7B},
    {0x85, 0x86}, {0x86, 0x8E}, {0x87, 0x97}, {0x88, 0xA4}, {0x89, 0xAF}, {0x8A, 0xC5}, {0x8B, 0xD7},
    {0x8C, 0xE8}, {0x8D, 0x20},
    {0x94, 0xB0}, {0x95, 0x9D}, {0x96, 0x13}, {0x97, 0x16}, {0x98, 0x7B}, {0x99, 0x91}, {0x9A, 0x1E},
    {0x9B, 0x08}, {0x9C, 0x20}, {0x9E, 0x81}, {0xA6, 0x06},
    {0x13, 0xFF},  // COM8: auto gain / exposure / white balance
    {0xFF, 0xFF},  // end marker
};
